# ---------------------------------------------------------------- helpers
def cord_clip(cords, x0, x1, y1):
    """Clip polygon = a big box with a slot cut along each drawstring, so a print slides UNDER the cords.
    cords: [(centreline points from the eyelet down to the aglet tip, half width), ...]"""
    pts = [(x0, min(c[0][0][1] for c in cords))]
    for cord, hw in sorted(cords, key=lambda c: c[0][0][0]):
        A, B = [], []
        for i, (x, y) in enumerate(cord):
            a, b = cord[max(i - 1, 0)], cord[min(i + 1, len(cord) - 1)]
            dx, dy = b[0] - a[0], b[1] - a[1]; n = math.hypot(dx, dy); nx, ny = -dy / n, dx / n
            A.append((x + hw * nx, y + hw * ny)); B.append((x - hw * nx, y - hw * ny))
        if A[1][0] > B[1][0]: A, B = B, A
        (ex, ey), (px, py) = cord[-1], cord[-2]; n = math.hypot(ex - px, ey - py)
        pts += A + [(ex + (ex - px) / n * hw, ey + (ey - py) / n * hw)] + B[::-1]
    pts += [(x1, min(c[0][0][1] for c in cords)), (x1, y1), (x0, y1)]
    return pts


def hoodie_v(cx, cy, w, rot, cords, light=135, **kw):
    d = dict(logo='v', rect=(cx, cy, w), rot=rot, fx='print', color=HOOD_INK, opacity=0.93, tex=0.55, soft=0.35, light=light,
             clip=cord_clip(cords, cx - w, cx + w, cy + w))
    d.update(kw); return d

def polo_h(cx, cy, w, rot=0, light=135, **kw):   # embroidered horizontal signature, wine thread
    d = dict(logo='h', rect=(cx, cy, w), rot=rot, fx='embroidery', color=WINE, angle=0, period=3.0, light=light,
             raised=1.4, tex=0.85, soft=0.4)
    d.update(kw); return d

def cap_v(plane, light=150, **kw):               # embroidered vertical signature centred on the cap's front seam
    d = dict(logo='v', plane=plane, fx='embroidery', color=CAP_THREAD, angle=-35, period=3.2, light=light,
             raised=1.6, tex=0.5, soft=0.45)      # tex 0.5: the logo straddles the sunlit and the shaded front panel
    d.update(kw); return d

def tote_print(logo, cx, cy, w, rot=0.0, light=160, **kw):
    d = dict(logo=logo, rect=(cx, cy, w), rot=rot, fx='print', color=TOTE_INK, opacity=0.9, tex=0.75, soft=0.4, light=light)
    d.update(kw); return d


